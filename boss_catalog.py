def catalog_seed():
    known = {'Grand Master Oberon': ('grand-master-oberon', ['oberon']),
             'Scarlett Etzel': ('scarlett-etzel', ['scarlett']),
             'Drume': ('drume', ['drumi'])}
    bases = Counter(name.split(' (')[0].lower() for name, _, _ in BOSSES)
    result = []
    for name, category, pageid in BOSSES:
        boss_id, aliases = known.get(name, (f'wiki-{pageid}', []))
        aliases = list(aliases)
        # "Arkhothep (Criatura)" fica falável como "Arkhothep" quando o nome curto é único.
        base = name.split(' (')[0]
        if base != name and bases[base.lower()] == 1:
            aliases.append(base)
        result.append(dict(boss_id=boss_id, name=name, aliases=aliases, category=category or 'unknown',
                           cooldown_type='unknown', cooldown_minutes=None,
                           source=f'https://www.tibiawiki.com.br/index.php?curid={pageid}',
                           verified_at=VERIFIED_AT, status='partial'))
    return result
